"""chart-2-binned-distributions.py

Self-contained: the Moving Frontiers house style, the data and the chart in one file. Run it with
matplotlib, numpy, pandas and Pillow available:

    python chart-2-binned-distributions.py

It writes chart-2-binned-distributions.png and chart-2-binned-distributions.csv into the working directory.

The world population in 2025 by daily income or consumption per person, stacked by Maddison region,
with the 40 percent line of the frontier mean (the population-weighted mean income of the US, Canada,
Australia and New Zealand) and the share of people below and above it.

DATA
Derived from the World Bank 1000 Binned Global Distribution (Poverty and Inequality Platform, March
2026 vintage, 2021 PPP), lined up to 2025: 218 economies, 1,000 sorted welfare bins each. Embedded
below are the results of that calculation, not the 218,000 bins themselves:
  * density curves: for each region, a Gaussian kernel (bandwidth 0.08 in log welfare) over every
    bin of every economy in the region, weighted by population, on a log grid from $0.40 to $800 a
    day in steps of 0.01; the value is millions of people per 5 percent step in income, so each
    curve integrates to the region's population;
  * FRONTIER_MEAN: population-weighted mean of the bins of USA, CAN, AUS and NZL, $ a day;
  * SHARE_BELOW: share of the world's population below 40% of that mean, read from each economy's
    sorted bins with linear interpolation between bin means.
Regions follow the Maddison Project Database 2023; 46 small economies outside it are assigned by
geography and 17 Pacific island economies, with no Maddison region, form their own band.
"""
