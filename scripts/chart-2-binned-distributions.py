def plot(w, h):
    fig = mf.new_fig(w, h)
    bot = 210/h
    ax = fig.add_axes([0.075, bot, 0.66, 1-bot-0.01])
    X = np.exp(LG)
    ax.stackplot(X, [D[r] for r in STACK], colors=[COL[r] for r in STACK], linewidth=0)
    ax.set_xscale('log'); ax.set_xlim(0.4, 800); ax.minorticks_off()
    mf.style_axes(ax, axis='y')
    mf.set_ticks(ax, [1, 2, 5, 10, 20, 50, 100, 200, 500], 'x', fmt='${:g}')
    mf.set_ticks(ax, [0, 50, 100, 150], 'y')
    ax.set_xlabel('Income or consumption per person per day (2021 PPP dollars, log scale)', loc='left', color=mf.INK, labelpad=16, **mf.arial(mf.T_XLAB, bold=True))
    ax.set_ylabel('Millions of people', color=mf.INK, labelpad=14, **mf.arial(mf.T_XLAB, bold=True))
    YT = TOP*1.27; ax.set_ylim(0, YT)
    mf.zero_line(ax, at=Z40, axis='x', span=(0, YT*0.985))
    ax.vlines(Z, 0, TOP*0.62, colors=mf.GREY_TXT, lw=1.8, zorder=4)
    lab_h = mf.T_LAB*1.15*mf.PX                         # one label line, in points
    top = dict(xycoords=('data', 'axes fraction'), textcoords='offset points', va='top', annotation_clip=False)
    ax.annotate(f'40% of frontier mean\n${Z40:.0f} a day', (Z40, 0.985), (-12, 0), ha='right', color=mf.LABEL, linespacing=1.15, **top, **mf.cal(mf.T_LAB))
    ax.annotate(f'{SB*100:.0f}% below', (Z40, 0.985), (-12, -2*lab_h - 14), ha='right', color=mf.RED, **top, **mf.cal(mf.T_HDR, bold=True))
    ax.annotate(f'{(1-SB)*100:.0f}% above', (Z40, 0.985), (12, -2*lab_h - 14), ha='left', color=mf.NAVY, **top, **mf.cal(mf.T_HDR, bold=True))
    ax.text(Z*1.05, TOP*0.62, f'Frontier mean\n${Z:.0f} a day', ha='left', va='top', color=mf.LABEL, linespacing=1.15, **mf.cal(mf.T_LAB))
    leg = ax.legend(handles=[Patch(color=COL[r], label=SHORT.get(r, r)) for r in STACK[::-1]], loc='center left',
                    bbox_to_anchor=(1.03, 0.5), ncol=1, frameon=False, prop=mf.P_CAL,
                    handlelength=1.2, handleheight=1.0, labelspacing=0.55, borderaxespad=0)
    for t in leg.get_texts(): t.set_fontsize(mf.T_LEG*mf.PX); t.set_color(mf.LABEL)
    fig.canvas.draw()
    r = leg.get_window_extent().x1/w
    if r > 0.995 or r < 0.985:
        pos = ax.get_position(); ax.set_position([pos.x0, pos.y0, pos.width + (0.99 - r), pos.height])
    return fig

