def cohorts(t0, T):
    """Rebuild the per-cohort aggregates from the embedded records."""
    rib, gin = {}, {}
    for kind, nm, o, d, base, gl, gm, gh, end in COHORTS[(t0, T)]:
        if kind == 'e':
            gin[d] = gin.get(d, 0.0) + end
            continue
        assert abs(base + gl + gm + gh - end) < 1e-6, nm
        r = rib.setdefault((o, d), dict(base=0.0, n=0,
                                        growth={g: 0.0 for g in GROUPS}))
        r['base'] += base
        r['n'] += 1
        for g, w in zip(GROUPS, (gl, gm, gh)):
            r['growth'][g] += w
    return rib, gin


