"""
chart-11-how-population-growth-and-reclassification-affect-income-group-size
============================================================================

Self-sufficient. Needs only Python plus numpy and matplotlib. Run it in an empty
directory:

    python3 chart-11-how-population-growth-and-reclassification-affect-income-group-size.py

Writes chart-11-...-income-group-size.png and .csv.

-----------------------------------------------------------------------------
PROVENANCE
-----------------------------------------------------------------------------
Sources, frozen and embedded below. Do not swap the embedded table for a live
call, a download, or a re-read of the workbook: the output is pinned to these
vintages and must run offline.

  World Bank, Country Analytical History (OGHIST), July 2026 vintage
      income classification of each economy, 1987 to 2025
  World Bank, World Development Indicators, SP.POP.TOTL
      population to 2025
  United Nations, World Population Prospects 2024, medium variant
      population from 2026, rebased to each economy's 2025 level

  Classification from 2026 and population from 2026 are PROJECTIONS produced by
  the author's workbook income-classification-2050.xlsx, not read from any
  publisher. Each economy grows at its decade-median rate subject to a floor
  equal to threshold drift and a group-specific cap, 21 economies are held at
  their 2025 class, and no economy is downgraded after 2025.

  Freeze date: 28 August 2026, from income-classification-2050.xlsx.

DERIVED VALUES
  COHORTS is derived, not raw. Each record is one economy in one panel, and its
  three growth fields are the sum of that economy's annual population changes
  credited to the group it held at the start of each year. Those annual series
  are not recoverable from this file.
  LEVELS is embedded rather than summed from COHORTS because the original read
  totalled with pandas, whose pairwise summation differs from a left-to-right
  Python sum in the last few bits. The script asserts the two agree to 1e-9.
  CHINA_HIC_YEAR is read off the projected annual classification and likewise
  cannot be recomputed from COHORTS. It defends a caption claim.

DUPLICATION
  COHORTS and LEVELS also appear in
  chart-10-how-country-income-groups-fill-up.py. The duplication is deliberate
  so that each file stays single-file self-sufficient.

-----------------------------------------------------------------------------
METHOD
-----------------------------------------------------------------------------
Each bar is the population of one income group in the year shown, split by where
those people came from over the preceding 25 years:

  already in the group   what the economies already there held at the start
  arrived by upward
    reclassification     what the economies that climbed in held in the year
                         they moved, so it carries their growth up to that point
  population growth      everything after that: growth of the economies that
                         stayed, growth of new members from the year they
                         arrived, and economies entering the classification

An economy reclassified downward into a group is counted with those already
there. There is one such case, Syria into low income, worth 0.02 billion.

The three parts sum to the bar exactly. A negative share means the members lost
population, which is what high income does after China joins in 2026: its two
positive parts exceed the group total and the difference is shown below the axis,
with a rule marking the true level.
"""
